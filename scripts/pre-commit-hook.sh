#!/bin/sh

# Автоматическая проверка роадмапа перед коммитом
# Устанавливается в .git/hooks/pre-commit

echo "🔍 Проверка соответствия роадмапа..."

# Запускаем автоматическую проверку
node scripts/roadmap-checker.js

# Получаем результат проверки
exit_code=$?

if [ $exit_code -ne 0 ]; then
    echo "❌ Проверка роадмапа не пройдена!"
    echo "Пожалуйста, обновите роадмап или исправьте код перед коммитом."
    exit 1
fi

echo "✅ Проверка роадмапа пройдена успешно!"
exit 0